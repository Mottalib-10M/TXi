const LIMITE = "(?<![\\p{L}\\p{N}'’-])";
const FIN = "(?![\\p{L}\\p{N}'’-])";

function echapper(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Mots seuls traduits partout : exonymes sans ambiguïté. Les autres mots
 * seuls (« Château », « Forêt », « Plage »…) ouvrent souvent un nom propre
 * absent du dictionnaire (« Château de Chambord ») ; on ne les traduit que
 * comme élément entier d'une liste, avec ITEMS_EN.
 */
const MOTS_SURS = new Set([
  "Allemagne", "Anvers", "Bade", "Bade-Wurtemberg", "Belgique", "Bourgogne", "Bretagne",
  "Bruxelles", "Catalogne", "Corse", "Courtrai", "Espagne", "Flandre", "Forêt-Noire",
  "Gascogne", "Gênes", "Italie", "Ligurie", "Normandie", "Pays-Bas", "Picardie", "Piémont",
  "Pyrénées", "Rhin", "Sarre", "Savoie", "Suisse", "Wallonie", "Alpes", "Méditerranée",
  "Navette", "Périphérique", "Rocade", "Francilienne", "Porte-à-porte",
  "Frontaliers", "Transfrontalier", "Transmanche", "périphérique", "gratuite",
]);
for (const k of Object.keys(PHRASES_EN)) {
  if (!/\s/.test(k) && !MOTS_SURS.has(k)) {
    if (!(k in ITEMS_EN)) ITEMS_EN[k] = PHRASES_EN[k];
    delete PHRASES_EN[k];
  }
}

// Les entrées identiques restent dans le motif d'anglaiser() : elles protègent
// un nom propre (« Suisse Normande ») de la traduction d'un mot qu'il contient.

const ITEMS_TRIES = Object.keys(ITEMS_EN).sort((a, b) => b.length - a.length);
// Un élément de liste : précédé d'un début de phrase ou d'une virgule, suivi
// d'une virgule, de « and », d'un point ou de « along the way / en route ».
const MOTIF_ITEMS = new RegExp(
  `(^|\\. |, |and )(${ITEMS_TRIES.map(echapper).join("|")})(?=,| and | en route| along the way|\\.|$)`,
  "gu",
);

function majusculeDebut(s: string): string {
  return s.replace(new RegExp("(^|[.!?]\\s+)(\\p{Ll})", "gu"), (_, a: string, b: string) => a + b.toUpperCase());
}

/** Traduit les passages français connus d'un texte anglais. */
export function anglaiser(texte: string, noms: Record<string, string> = {}): string {
  // Les noms de départ et d'arrivée entrent dans le même motif que les
  // libellés : le plus long l'emporte, si bien que « Cathédrale de Rouen » est
  // traduit en entier, tandis que « Alpes » n'est pas touché dans le nom
  // « Aéroport Lyon Saint-Exupéry » (rendu « Lyon Saint-Exupéry Airport »).
  const table: Record<string, string> = { ...PHRASES_EN };
  for (const [nom, en] of Object.entries(noms)) {
    const n = nom.normalize("NFC");
    if (n && !(n in PHRASES_EN)) table[n] = en.normalize("NFC");
  }
  const cles = Object.keys(table).sort((a, b) => b.length - a.length);
  const motif = new RegExp(`${LIMITE}(?:${cles.map(echapper).join("|")})${FIN}`, "gu");
  // Certaines saisies sont en Unicode décomposé (« e » + accent combinant) :
  // on recompose pour que « Aéroport Beauvais-Tillé » soit reconnu.
  let s = texte.normalize("NFC");
  for (const [m, remplacement] of ITINERAIRES) s = s.replace(m, remplacement);
  s = s.replace(motif, (m) => table[m]);
  s = s.replace(MOTIF_ITEMS, (_, avant: string, m: string) => avant + ITEMS_EN[m]);
  return majusculeDebut(s);
}

/** Un point fort, traduit pour la liste visible de la page anglaise. */
export function pointFortEn(point: string): string {
  const h = point.normalize("NFC");
  const t = ITEMS_EN[h] ?? PHRASES_EN[h] ?? anglaiser(h);
  return t.charAt(0).toUpperCase() + t.slice(1);
}

/** Itinéraire habituel (champ autoroute, saisi en français). */
export function autorouteEn(autoroute: string): string {
  const s = anglaiser(autoroute);
  // Au milieu de « The usual route takes … », un nom commun reste en minuscule.
  return /^(Southern|Western|Eastern|Lower|Middle|Ring|Direct|Paris ring)\b/.test(s)
    ? "the " + s.charAt(0).toLowerCase() + s.slice(1)
    : s;
}

