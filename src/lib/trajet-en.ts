/**
 * Champ péages (saisi en français : « ~4 € (inclus) », « Gratuit (voie
 * express bretonne) ») rendu pour « The usual route takes …, with ___ ».
 */
export function peagesEn(peages: string): string {
  const p = peages.normalize("NFC").trim();
  const prix = (n: string) => `~€${n.replace(",", ".")}`;
  let m = p.match(/^gratuit \((D\d+)\) ou ~(\d+(?:,\d+)?) € \((A\d+)\)$/i);
  if (m) return `no tolls via the ${m[1]}, or ${prix(m[2])} in tolls via the ${m[3]}`;
  m = p.match(/^Péage (A\d+) environ (\d+(?:,\d+)?) €$/);
  if (m) return `${prix(m[2])} in tolls (${m[1]})`;
  m = p.match(/^Environ (\d+(?:,\d+)?) € de péage sur l'(A\d+)$/);
  if (m) return `${prix(m[1])} in tolls on the ${m[2]}`;
  m = p.match(/^(?:gratuite?|aucun(?: péage)?|0 €)(.*)$/i);
  if (m) {
    let suite = m[1];
    for (const [r, en] of SANS_PEAGE) if (r.test(suite)) { suite = suite.replace(r, en); break; }
    return `no tolls${suite}`;
  }
  m = p.match(/^~(\d+(?:,\d+)?) €(.*)$/);
  if (m) {
    let suite = m[2];
    for (const [r, en] of PEAGES_SUITE) suite = suite.replace(r, en);
    return `${prix(m[1])} in tolls${suite}`;
  }
  return anglaiser(p);
}

/** Fourchette de prix saisie en français (« 50 — 62 € »). */
export function prixEstimeEn(prix: string): string {
  const m = prix.normalize("NFC").match(/^(\d+)\s*[—–-]\s*(\d+)\s*€$/);
  if (m) return `€${m[1]} to €${m[2]}`;
  const u = prix.match(/^(\d+)\s*€$/);
  return u ? `€${u[1]}` : prix;
}
